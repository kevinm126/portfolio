/**
 * Copies the onnxruntime-web wasm runtime into public/ml/ort/<version>/ so the
 * ML Lab page can load it same-origin (the CSP's connect-src 'self' blocks the
 * package's default CDN path). Runs on predev/prebuild, so Vercel builds get
 * the files too; public/ml/ort/ is gitignored.
 *
 * Also writes src/components/ml/ort-version.ts (committed) so the client
 * requests the exact version that was installed. If onnxruntime-web ever
 * renames its dist files, this script fails the build loudly instead of
 * shipping a page that 404s at runtime.
 */

import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkgPath = join(root, "node_modules", "onnxruntime-web", "package.json");
const distDir = join(root, "node_modules", "onnxruntime-web", "dist");

const FILES = ["ort-wasm-simd-threaded.wasm", "ort-wasm-simd-threaded.mjs"];

const version = JSON.parse(readFileSync(pkgPath, "utf8")).version;
const outDir = join(root, "public", "ml", "ort", version);

for (const f of FILES) {
  if (!existsSync(join(distDir, f))) {
    console.error(
      `sync-ort-assets: expected ${f} in onnxruntime-web@${version}/dist but it is missing.\n` +
        "The package likely renamed its wasm artifacts; update scripts/sync-ort-assets.mjs and model.ts.",
    );
    process.exit(1);
  }
}

const ortRoot = join(root, "public", "ml", "ort");
if (existsSync(ortRoot)) {
  for (const entry of readdirSync(ortRoot)) {
    if (entry !== version) rmSync(join(ortRoot, entry), { recursive: true, force: true });
  }
}
mkdirSync(outDir, { recursive: true });
for (const f of FILES) copyFileSync(join(distDir, f), join(outDir, f));

const versionFile = join(root, "src", "components", "ml", "ort-version.ts");
const contents =
  "// Generated by scripts/sync-ort-assets.mjs; do not edit by hand.\n" +
  `export const ORT_VERSION = "${version}";\n`;
mkdirSync(dirname(versionFile), { recursive: true });
if (!existsSync(versionFile) || readFileSync(versionFile, "utf8") !== contents) {
  writeFileSync(versionFile, contents);
}

console.log(`sync-ort-assets: onnxruntime-web ${version} -> public/ml/ort/${version}/`);
